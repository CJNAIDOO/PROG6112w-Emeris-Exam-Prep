    // ===================== Task 6.1 =====================
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        StudentMarks sm = calculateAndDisplay();   // makes sure what we save is valid and up to date
        if (sm == null) {
            return;
        }

        try {
            FileWriter writer = new FileWriter("studentmarks.txt");
            writer.write(buildReport(sm));
            writer.close();
            JOptionPane.showMessageDialog(this, "Marks saved to studentmarks.txt");
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Could not save the file: " + e.getMessage(),
                    "File error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    // ===================== Task 6.2 =====================
    private void btnLoadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadActionPerformed
        try {
            BufferedReader reader = new BufferedReader(new FileReader("studentmarks.txt"));

            reader.readLine();                 // line 1: "STUDENT MARKS REPORT" (skip)
            reader.readLine();                 // line 2: "*****" (skip)
            String line1 = reader.readLine();  // "Student 1: 70, 60"
            String line2 = reader.readLine();  // "Student 2: 40, 80"
            String line3 = reader.readLine();  // "Student 3: 30, 90"
            reader.close();

            fillFields(line1, txtStudent1Test1, txtStudent1Test2);
            fillFields(line2, txtStudent2Test1, txtStudent2Test2);
            fillFields(line3, txtStudent3Test1, txtStudent3Test2);

            calculateAndDisplay();             // recalculate with the loaded marks

        } catch (FileNotFoundException e) {
            // Challenge question: Load clicked before anything was saved
            JOptionPane.showMessageDialog(this,
                    "No saved file found. Enter marks and click Save first.",
                    "Nothing to load", JOptionPane.WARNING_MESSAGE);
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Could not read the file: " + e.getMessage(),
                    "File error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoadActionPerformed

