    // ===================== Task 5.1 + 5.3 =====================
    // Reads the six text fields into a 3x2 array.
    // Returns null if any mark is invalid.
    private int[][] captureMarks() {
        int[][] marks = new int[3][2];

        try {
            // getText() returns a String; Integer.parseInt() turns it into an int.
            // "abc" or an empty field makes parseInt throw a NumberFormatException.
            marks[0][0] = Integer.parseInt(txtStudent1Test1.getText().trim());
            marks[0][1] = Integer.parseInt(txtStudent1Test2.getText().trim());
            marks[1][0] = Integer.parseInt(txtStudent2Test1.getText().trim());
            marks[1][1] = Integer.parseInt(txtStudent2Test2.getText().trim());
            marks[2][0] = Integer.parseInt(txtStudent3Test1.getText().trim());
            marks[2][1] = Integer.parseInt(txtStudent3Test2.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Every field must contain a whole number (no letters, no empty fields).",
                    "Invalid input", JOptionPane.ERROR_MESSAGE);
            return null;
        }

        // Numbers like 120 or -5 parse fine, so check the range separately
        for (int row = 0; row < marks.length; row++) {
            for (int col = 0; col < marks[row].length; col++) {
                if (marks[row][col] < 0 || marks[row][col] > 100) {
                    JOptionPane.showMessageDialog(this,
                            "Student " + (row + 1) + ", Test " + (col + 1)
                            + ": marks must be between 0 and 100.",
                            "Invalid input", JOptionPane.ERROR_MESSAGE);
                    return null;
                }
            }
        }
        return marks;
    }

    // Builds the report text. Used by Calculate (screen) AND Save (file),
    // so the report only has to be written once.
    private String buildReport(StudentMarks sm) {
        int[][] marks = sm.GetMarks();
        String report = "STUDENT MARKS REPORT\n";
        report += "****************************\n";

        for (int row = 0; row < marks.length; row++) {
            report += "Student " + (row + 1) + ": " + marks[row][0] + ", " + marks[row][1] + "\n";
        }

        report += "Total Marks: " + sm.GetTotalMarks() + "\n";
        report += "Average Mark: " + String.format("%.2f", sm.GetAverageMarks()) + "\n";
        report += "Passing Marks: " + sm.GetPassCount() + "\n";
        report += "Failing Marks: " + sm.GetFailCount() + "\n";
        report += "Students Processed: " + sm.GetStudentsProcessed() + "\n";
        report += "****************************\n";
        return report;
    }

    // ===================== Task 5.2 =====================
    // Capture -> create object -> calculate -> display.
    // Returns the object (or null if input was invalid) so Save can reuse it.
    private StudentMarks calculateAndDisplay() {
        int[][] marks = captureMarks();          // 1. capture
        if (marks == null) {
            return null;                         // invalid input, so stop here
        }

        StudentMarks sm = new StudentMarks(marks);   // 2 + 3. create object, pass array

        txtResults.setText(buildReport(sm));         // 4 + 5. calculate and display
        lblStudentsProcessed.setText("Students processed: " + sm.GetStudentsProcessed()); // 6.
        return sm;
    }

    // Splits a line like "Student 1: 70, 60" and puts 70 and 60 into two text fields
    private void fillFields(String line, JTextField test1, JTextField test2) {
        String marksPart = line.split(":")[1];   // " 70, 60"
        String[] parts = marksPart.split(",");   // [" 70", " 60"]
        test1.setText(parts[0].trim());          // "70"
        test2.setText(parts[1].trim());          // "60"
    }

